#!/usr/bin/env python3
"""Rebuild a lapis Linux Image = freshly built shim + LAPISXNU payload whose
kernel segments come from a base Image (CI kernel) with xnu_binpatches applied
and whose ADT is regenerated by mkadt.py.

usage: repack.py BASE_IMAGE SHIM_IMAGE ADT OUT_IMAGE [--extra mod.py]"""
import struct, sys, os, importlib.util
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
from xnu_binpatches import PATCHES

def main():
    base, shim, adt, out = sys.argv[1:5]
    patches = list(PATCHES)
    if '--extra' in sys.argv:
        spec = importlib.util.spec_from_file_location('extra', sys.argv[sys.argv.index('--extra') + 1])
        mod = importlib.util.module_from_spec(spec); spec.loader.exec_module(mod); patches += mod.PATCHES
    b = open(base, 'rb').read(); off = b.find(b'LAPISXNU'); p = bytearray(b[off:])
    ver, nsegs = struct.unpack_from('<II', p, 8)
    virt, entry, adt_off, adt_sz, kend, phys, msz = struct.unpack_from('<7Q', p, 16)
    segs = [struct.unpack_from('<4Q', p, 0x448 + 32 * i) for i in range(nsegs)]
    def foff(va):
        for vm, vs, fo, fs in segs:
            if vm <= va < vm + fs: return fo + va - vm
        raise ValueError(hex(va))
    for name, va, old, new in patches:
        o = foff(va); cur = list(struct.unpack_from('<%dI' % len(new), p, o))
        if cur == new: print(f'  {name}: already applied'); continue
        if isinstance(old, str):   # region identified by sha256
            import hashlib
            assert hashlib.sha256(bytes(p[o:o + 4 * len(new)])).hexdigest() == old, name
        else:
            assert cur[:len(old)] == old, (name, [hex(x) for x in cur])
        struct.pack_into('<%dI' % len(new), p, o, *new); print(f'  {name}: applied @ {va:#x}')
    if '--cmdline' in sys.argv:
        cl = sys.argv[sys.argv.index('--cmdline') + 1].encode()
        assert len(cl) < 1024
        p[0x48:0x48 + 1024] = cl + b'\0' * (1024 - len(cl))
        print(f'  cmdline: {cl.decode()}')
    a = open(adt, 'rb').read()
    p = p[:adt_off] + a
    while len(p) % 8: p += b'\0'
    struct.pack_into('<Q', p, 0x28, len(a))
    s = bytearray(open(shim, 'rb').read())
    assert s[56:60] == b'ARM\x64'
    img = s + p
    struct.pack_into('<Q', img, 16, len(img))
    open(out, 'wb').write(img)
    print(f'{out}: {len(img)} bytes (shim {len(s):#x}, adt {len(a):#x})')
main()
