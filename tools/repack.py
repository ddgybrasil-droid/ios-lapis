#!/usr/bin/env python3
"""Rebuild a lapis Linux Image = freshly built shim + LAPISXNU payload whose
kernel segments come from a base Image (CI kernel) with xnu_binpatches applied
and whose ADT is regenerated by mkadt.py.

usage: repack.py BASE_IMAGE SHIM_IMAGE ADT OUT_IMAGE [--extra mod.py]
                 [--cmdline "..."] [--ramdisk IMAGE]

--ramdisk appends IMAGE as an extra payload segment right after the kernel
(page-aligned), bumps kernel_end past it, and adds /chosen/memory-map RAMDisk
=<phys,size> so IOFindBSDRoot creates md0. Boot with rd=md0.
"""
import struct, sys, os, importlib.util, hashlib
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
from xnu_binpatches import PATCHES
import adt
PAGE = 0x4000

def add_ramdisk_to_adt(adt_blob, phys, size):
    root, _ = adt.parse(adt_blob)
    chosen = next(c for c in root.children if c.name == 'chosen')
    mmap = next(c for c in chosen.children if c.name == 'memory-map')
    assert mmap.prop('RAMDisk') is None, 'ADT already has a RAMDisk'
    mmap.props.append(('RAMDisk', 0, struct.pack('<2Q', phys, size)))
    return adt.serialize(root)

def main():
    base, shim, adt_path, out = sys.argv[1:5]
    patches = list(PATCHES)
    if '--extra' in sys.argv:
        spec = importlib.util.spec_from_file_location('extra', sys.argv[sys.argv.index('--extra') + 1])
        mod = importlib.util.module_from_spec(spec); spec.loader.exec_module(mod); patches += mod.PATCHES
    cmdline = None
    if '--cmdline' in sys.argv:
        cmdline = sys.argv[sys.argv.index('--cmdline') + 1]
    ramdisk_ext = None
    if '--ramdisk-ext' in sys.argv:
        # emu-only: ramdisk is NOT embedded; QEMU '-device loader' places it at
        # the printed PA. We only reserve [kend, kend+size) and describe it in the ADT.
        ramdisk_ext = sys.argv[sys.argv.index('--ramdisk-ext') + 1]
    ramdisk_path = None
    if '--ramdisk' in sys.argv:
        ramdisk_path = sys.argv[sys.argv.index('--ramdisk') + 1]

    b = open(base, 'rb').read(); off = b.find(b'LAPISXNU'); p = bytearray(b[off:])
    ver, nsegs = struct.unpack_from('<II', p, 8)
    virt, entry, adt_off, adt_sz, kend, phys, msz = struct.unpack_from('<7Q', p, 16)
    segs = [list(struct.unpack_from('<4Q', p, 0x448 + 32 * i)) for i in range(nsegs)]
    def foff(va):
        for vm, vs, fo, fs in segs:
            if vm <= va < vm + fs: return fo + va - vm
        raise ValueError(hex(va))
    for name, va, old, new in patches:
        o = foff(va); cur = list(struct.unpack_from('<%dI' % len(new), p, o))
        if cur == new: print(f'  {name}: already applied'); continue
        if isinstance(old, str):
            assert hashlib.sha256(bytes(p[o:o + 4 * len(new)])).hexdigest() == old, name
        else:
            assert cur[:len(old)] == old, (name, [hex(x) for x in cur])
        struct.pack_into('<%dI' % len(new), p, o, *new); print(f'  {name}: applied @ {va:#x}')

    a = open(adt_path, 'rb').read()

    if ramdisk_ext:
        import os
        rd_size = (os.path.getsize(ramdisk_ext) + PAGE - 1) & ~(PAGE - 1)
        rd_va = (kend + PAGE - 1) & ~(PAGE - 1)
        rd_pa = rd_va - virt + phys
        a = add_ramdisk_to_adt(a, rd_pa, rd_size)
        kend = rd_va + rd_size
        struct.pack_into('<Q', p, 0x10 + 8 * 4, kend)
        open(out + '.ramdisk-pa', 'w').write(f'{rd_pa:#x} {os.path.abspath(ramdisk_ext)}\n')
        print(f'  ramdisk-ext: pa={rd_pa:#x} size={rd_size:#x} va={rd_va:#x} (load with QEMU -device loader)')

    if ramdisk_path:
        # Rebuild payload: copy patched kernel segments, append ramdisk, new ADT.
        image = open(ramdisk_path, 'rb').read()
        rd_size = (len(image) + PAGE - 1) & ~(PAGE - 1)
        rd_va = (kend + PAGE - 1) & ~(PAGE - 1)
        new_kend = rd_va + rd_size
        rd_pa = rd_va - virt + phys
        a = add_ramdisk_to_adt(a, rd_pa, rd_size)
        print(f'  ramdisk: pa={rd_pa:#x} size={rd_size:#x} va={rd_va:#x}')

        pieces = []
        for vm, vs, fo, fs in segs:
            pieces.append((vm, vs, bytes(p[fo:fo+fs])))
        pieces.append((rd_va, rd_size, image + b'\0' * (rd_size - len(image))))

        hdr_size = 0x448 + 32 * len(pieces)
        outp = bytearray(hdr_size)
        seg_table = []
        for vmaddr, vmsize, data in pieces:
            off = len(outp)
            outp += data
            outp += b'\0' * (-len(outp) & 0xf)
            seg_table.append((vmaddr, vmsize, off, len(data)))
        adt_off = len(outp)
        outp += a
        outp += b'\0' * (-len(outp) & 0xf)
        struct.pack_into('<8sII', outp, 0, b'LAPISXNU', 1, len(pieces))
        struct.pack_into('<7Q', outp, 0x10, virt, entry, adt_off, len(a), new_kend, phys, msz)
        cl = (cmdline or '').encode()[:1023]
        outp[0x48:0x48+1024] = cl + b'\0' * (1024 - len(cl))
        if cmdline: print(f'  cmdline: {cmdline}')
        for i, t in enumerate(seg_table):
            struct.pack_into('<4Q', outp, 0x448 + 32 * i, *t)
        p = outp
    else:
        if cmdline is not None:
            cl = cmdline.encode()
            assert len(cl) < 1024
            p[0x48:0x48 + 1024] = cl + b'\0' * (1024 - len(cl))
            print(f'  cmdline: {cl.decode()}')
        p = p[:adt_off] + a
        while len(p) % 8: p += b'\0'
        struct.pack_into('<Q', p, 0x28, len(a))

    s = bytearray(open(shim, 'rb').read())
    assert s[56:60] == b'ARM\x64'
    img = s + p
    struct.pack_into('<Q', img, 16, len(img))
    open(out, 'wb').write(img)
    print(f'{out}: {len(img)} bytes (shim {len(s):#x}, adt {len(a):#x})')
main()
